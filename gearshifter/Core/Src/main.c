/* --- Analog Hall sensor read (H1/H2) --- */
static uint32_t read_hall_channel(uint32_t channel)
{
    ADC_ChannelConfTypeDef sConfig = {0};
    sConfig.Channel = channel;
    sConfig.Rank = ADC_REGULAR_RANK_1;
    sConfig.SamplingTime = ADC_SAMPLETIME_56CYCLES;
    HAL_ADC_ConfigChannel(&hadc1, &sConfig);

    HAL_ADC_Start(&hadc1);
    HAL_ADC_PollForConversion(&hadc1, 10);
    uint32_t raw = HAL_ADC_GetValue(&hadc1);
    HAL_ADC_Stop(&hadc1);

    return raw;
}

/* --- SPI angle sensor read (AS5047-style protocol, 14-bit angle + 2 status bits) --- */
static uint16_t read_spi_angle(void)
{
    uint8_t tx[2] = {0xFF, 0xFF};
    uint8_t rx[2] = {0, 0};

    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_6, GPIO_PIN_SET);    /* CS high = select */
    HAL_Delay(1);
    HAL_SPI_TransmitReceive(&hspi1, tx, rx, 4, 100);
    HAL_Delay(1);
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_6, GPIO_PIN_RESET);  /* CS low = deselect */

    rxData[0] = rx[0];
    rxData[1] = rx[1];

    uint16_t raw = ((uint16_t)rx[2] << 8) | rx[3];
    return raw & 0x3FFF;
}

